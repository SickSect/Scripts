namespace Core.UI.Screens
{
    /// <summary>
    /// Блокирующий UI-экран (пауза, инвентарь, диалог, карта, компьютер...).
    /// Менеджер гарантирует, что открыт максимум один такой экран за раз.
    ///
    /// Экран НЕ трогает timeScale и ввод сам — это делает UIScreenManager один раз,
    /// иначе два экрана конфликтуют (как пауза vs инвентарь).
    /// </summary>
    public interface IUIScreen
    {
        bool IsOpen { get; }

        /// <summary>
        /// Останавливать ли время, пока экран открыт.
        ///
        /// true (по умолчанию) — меню: пауза, инвентарь, настройки.
        /// false — диегетические экраны внутри мира: компьютер, телевизор, автоответчик.
        /// Мир продолжает жить, ввод всё равно переключается на UI.
        /// </summary>
        bool PausesGame => true;

        /// <summary>Показать содержимое экрана (панель). Без timeScale/ввода.</summary>
        void OpenScreen();

        /// <summary>Скрыть содержимое экрана. Без timeScale/ввода.</summary>
        void CloseScreen();
    }
}
